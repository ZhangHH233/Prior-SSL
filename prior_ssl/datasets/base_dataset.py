import os
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset
import torchvision as T


GOALS_VALUE_MAP = {
    0: 0,
    80: 1,
    160: 2,
    255: 3,
}


def _as_channel_stats(value, in_channels):
    if isinstance(value, (int, float)):
        return [float(value)] * in_channels

    value = list(value)
    if len(value) == 1:
        return value * in_channels
    if len(value) != in_channels:
        raise ValueError(
            f"Normalization stats length {len(value)} "
            f"does not match in_channels={in_channels}"
        )
    return value


class BaseDataset(Dataset):
    """Image segmentation dataset with the sample style requested by the user."""

    def __init__(
        self,
        image_list,
        mask_list=None,
        image_size=(512, 512),
        num_classes=2,
        normalize_mean=0.5,
        normalize_std=0.5,
        augment=False,
        in_channels=3,
    ):
        self.image_list = [str(p) for p in image_list]
        self.mask_list = [str(p) for p in mask_list] if mask_list is not None else None
        self.image_size = tuple(image_size)
        self.num_classes = int(num_classes)
        self.in_channels = int(in_channels)
        self.augment = augment

        if self.mask_list is not None and len(self.image_list) != len(self.mask_list):
            raise ValueError("image_list and mask_list must have the same length")

        self.transformer = T.transforms.Compose(
            [
                T.transforms.ToTensor(),
                T.transforms.Normalize(
                    mean=_as_channel_stats(normalize_mean, self.in_channels),
                    std=_as_channel_stats(normalize_std, self.in_channels),
                ),
            ]
        )

    def __getitem__(self, index):
        image_file = self.image_list[index]
        image_mode = "L" if self.in_channels == 1 else "RGB"
        image = Image.open(image_file).convert(image_mode)
        width, height = image.size
        image = image.resize(self.image_size, Image.BILINEAR)

        do_flip = self.augment and torch.rand(1).item() > 0.5
        if do_flip:
            image = image.transpose(Image.FLIP_LEFT_RIGHT)

        image = self.transformer(image)

        sample = {
            "image": image,
            "image_file": str(image_file),
            "file_name": Path(image_file).name,
            "height": height,
            "width": width,
            "_flipped": do_flip,
        }

        if self.mask_list is not None:
            mask_file = self.mask_list[index]
            mask = self._load_mask(mask_file, do_flip=do_flip)
            sample["mask"] = mask
            sample["mask_file"] = str(mask_file)
            sample["is_pseudo"] = torch.tensor(False)
            sample["confidence"] = torch.ones_like(mask, dtype=torch.float32)
            sample["confidence_file"] = ""

        return sample

    def __len__(self):
        return len(self.image_list)

    def _load_mask(self, mask_file, do_flip=False):
        mask = Image.open(mask_file).convert("L")
        mask = mask.resize(self.image_size, Image.NEAREST)
        if do_flip:
            mask = mask.transpose(Image.FLIP_LEFT_RIGHT)
        mask_np = np.array(mask)
        if self.num_classes <= 2:
            mask_np = (mask_np > 0).astype(np.int64)
        else:
            unique_values = set(np.unique(mask_np).tolist())
            if unique_values.issubset(set(GOALS_VALUE_MAP.keys())):
                mapped = np.zeros_like(mask_np, dtype=np.int64)
                for raw_value, class_id in GOALS_VALUE_MAP.items():
                    mapped[mask_np == raw_value] = class_id
                mask_np = mapped
            else:
                mask_np = mask_np.astype(np.int64)
        return torch.from_numpy(mask_np)


class PseudoLabelDataset(BaseDataset):
    """Dataset for pseudo labels and confidence maps generated by confidence_evaluate.py."""

    def __init__(
        self,
        image_list,
        pseudo_mask_list,
        confidence_list=None,
        image_size=(512, 512),
        num_classes=2,
        normalize_mean=0.5,
        normalize_std=0.5,
        augment=False,
        in_channels=3,
    ):
        super().__init__(
            image_list=image_list,
            mask_list=pseudo_mask_list,
            image_size=image_size,
            num_classes=num_classes,
            normalize_mean=normalize_mean,
            normalize_std=normalize_std,
            augment=augment,
            in_channels=in_channels,
        )
        self.confidence_list = (
            [str(p) for p in confidence_list] if confidence_list is not None else None
        )

    def __getitem__(self, index):
        sample = super().__getitem__(index)
        sample["is_pseudo"] = torch.tensor(True)

        if self.confidence_list is not None:
            confidence_file = self.confidence_list[index]
            confidence = np.load(confidence_file).astype(np.float32)
            if confidence.shape != self.image_size[::-1]:
                confidence_img = Image.fromarray(confidence)
                confidence_img = confidence_img.resize(self.image_size, Image.BILINEAR)
                confidence = np.array(confidence_img).astype(np.float32)
            # Flip confidence if image was flipped
            if sample.pop("_flipped", False):
                confidence = np.fliplr(confidence)
            sample["confidence"] = torch.from_numpy(confidence)
            sample["confidence_file"] = str(confidence_file)

        return sample


# Backwards-compatible alias for code that follows the user's class name style.
Base_dataset = BaseDataset
